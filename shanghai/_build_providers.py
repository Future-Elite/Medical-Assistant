def npi(seed: str) -> str:
    """10 位机构代码，由名称确定性派生。

    这是**自造代码**，不是真实 NPI，也没有 NPI 校验位 —— 真实机构代码属于
    需要外部数据源才能填的字段，见 SOURCES.md。
    """
    h = hashlib.sha256(seed.encode("utf-8")).hexdigest()
    return "9" + "".join(str(int(c, 16) % 10) for c in h[:9])


def phone(seed: str) -> str:
    h = hashlib.sha256(("tel" + seed).encode("utf-8")).hexdigest()
    return "021-" + "".join(str(int(c, 16) % 10) for c in h[:8])


def address(seed: str, district: str) -> str:
    """示意性地址：区 + 常见路名 + 门牌号。**不是实际门牌号**。"""
    h = hashlib.sha256(("addr" + seed).encode("utf-8")).hexdigest()
    road = _ROADS[int(h[:2], 16) % len(_ROADS)]
    num = int(h[2:5], 16) % 1800 + 100
    return f"上海市{district}{road}{num}号"


def _plain_row(name: str, district: str, lat: float, lon: float, emergency: str) -> str:
    return ",".join([
        npi(name), name, address(name, district), district, "SH",
        "200000", "3101", f"{lat:.4f}", f"{lon:.4f}", phone(name), emergency,
    ])


