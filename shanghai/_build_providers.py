#: 等级没查证过的机构，格子里写这个而不是留空。
#: 留空会被下游当成"该字段不适用"，写上才能看出是**待核实**。
UNVERIFIED = "【待核实】"


def _org_types() -> dict[str, str]:
    """机构名称 -> 类型。"""
    out = {name: "综合医院" for name, *_ in HOSPITALS}
    out.update(TYPE_OVERRIDE)
    for district, street, *_ in COMMUNITY:
        out[f"上海市{district}{street}社区卫生服务中心"] = "社区卫生服务中心"
    for name, *_ in URGENT:
        out[name] = "急救中心"
    for name, *_ in VA:
        out[name] = TYPE_OVERRIDE.get(name, "综合医院")
    return out


def write_organization_levels() -> None:
    """产出 ``organization_levels.csv`` —— 导出层回填 机构.等级 / .类型 用。

    等级的数据源就是本文件 ``HOSPITALS`` 里的第 5 个字段，不再另抄一份 ——
    抄一份就会有第二处需要同步的地方。

    社区卫生服务中心与急救中心的等级**没有查证过**，一律写 ``【待核实】``：
    Synthea 的 ``Organization`` 里根本没有"等级"这个字段，这几个值全部是
    我们补的合成属性，投产前必须对着上海市卫健委的《医疗机构执业登记》
    公示核对（见 ``SOURCES.md``）。
    """
    types = _org_types()
    rows = [(name, grade, types[name]) for name, _d, _la, _lo, grade, _e in HOSPITALS]
    rows += [
        (f"上海市{d}{s}社区卫生服务中心", UNVERIFIED, "社区卫生服务中心")
        for d, s, *_ in COMMUNITY
    ]
    rows += [(n, UNVERIFIED, "急救中心") for n, *_ in URGENT]
    rows += [(n, UNVERIFIED, types[n]) for n, *_ in VA]

    lines = ["机构名称,等级,类型"]
    for name, grade, otype in rows:
        for cell in (name, grade, otype):
            if any(ch in cell for ch in ',"\r\n'):
                raise ValueError(f"值里不能出现逗号/引号/换行：{cell!r}")
        lines.append(f"{name},{grade},{otype}")
    path = Path(__file__).resolve().parent / "organization_levels.csv"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{'organization_levels.csv':32s} {len(rows):3d} 行")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)

    hosp_rows = []
    for name, district, lat, lon, _grade, emergency in HOSPITALS:
        cells = [
            npi(name), name, address(name, district), district, "SH",
            "200000", "3101", f"{lat:.4f}", f"{lon:.4f}", phone(name),
            "Yes" if emergency else "No", "true",
        ]
        cells += [str(SPECIALTY_MIX[k]) for k in SPECIALTY_MIX]
        hosp_rows.append(",".join(cells))

    files = {
        "hospitals.csv": [HOSP_HEADER] + hosp_rows,
        "primary_care_facilities.csv": [PC_HEADER] + [
            _plain_row(f"上海市{d}{s}社区卫生服务中心", d, la, lo, "No")
            for d, s, la, lo in COMMUNITY
        ],
        "urgent_care_facilities.csv": [PC_HEADER] + [
            _plain_row(n, d, la, lo, "No") for n, d, la, lo in URGENT
        ],
        "va_facilities.csv": [PC_HEADER] + [
            _plain_row(n, d, la, lo, "No") for n, d, la, lo in VA
        ],
    }

    for filename, lines in files.items():
        (OUT / filename).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{filename:32s} {len(lines) - 1:3d} 行")

    write_organization_levels()


if __name__ == "__main__":
    main()