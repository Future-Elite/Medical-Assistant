"""Export guideline chunks to the Medical-Assistant custom source contract."""

from __future__ import annotations

import json
from pathlib import Path

MAX_DOCUMENTS_PER_SOURCE = 40


def export_custom_source(chunks_path: Path, output_path: Path, source_id: str) -> int:
    chunks = [json.loads(line) for line in chunks_path.read_text(encoding="utf-8").splitlines() if line.strip()]
    if not chunks:
        raise ValueError(f"知识块文件为空：{chunks_path}")

    docs = []
    for item in chunks:
        guide_title = item.get("source_title") or item.get("source_id") or "中文医学指南"
        section = " > ".join(item.get("section_path") or [])
        page_start = item.get("page_start") or None
        page_end = item.get("page_end") or page_start
        locator = section or "指南正文"
        if page_start:
            locator += f"（第 {page_start} 页" + (f"–{page_end} 页" if page_end != page_start else "") + "）"
        metadata = {
            "chunk_id": item["chunk_id"],
            "specialty": item.get("specialty", ""),
            "section_path": item.get("section_path", []),
            "element_type": item.get("element_type", "text"),
            "evidence_level": item.get("evidence_level", ""),
            "recommendation_grade": item.get("recommendation_grade", ""),
            "source_file": item.get("source_file", ""),
            "page_start": page_start,
            "page_end": page_end,
            "image_refs": item.get("image_refs", []),
            "chunk_strategy": item.get("chunk_strategy", "structure"),
            "table_strategy": item.get("table_strategy", "markdown"),
            "figure_strategy": item.get("figure_strategy", "reference"),
        }
        document = {
            "document_id": item["chunk_id"],
            "kind": "guideline",
            # Medical-Assistant deduplicates by title + kind without DOI/PMID.
            "title": f"{guide_title} [{item['chunk_id']}]",
            "text": item.get("text", ""),
            "locator": locator,
            "metadata": {**metadata, "guide_title": guide_title},
        }
        if item.get("source_url"):
            document["url"] = item["source_url"]
        if item.get("version"):
            document["version_id"] = item["version"]
        if item.get("recommendation_grade"):
            document["recommendation_id"] = f"rec-{item['chunk_id']}"
        docs.append(document)

    sources = []
    for offset in range(0, len(docs), MAX_DOCUMENTS_PER_SOURCE):
        part = offset // MAX_DOCUMENTS_PER_SOURCE + 1
        sources.append({
            "source_id": f"{source_id}-{part:03d}",
            "kinds": ["guideline"],
            "description": "Guideline chunks generated by MedLLM guideline_processing",
            "version": chunks[0].get("version") or "unknown-version",
            "documents": docs[offset:offset + MAX_DOCUMENTS_PER_SOURCE],
        })
    existing_sources = []
    if output_path.is_file():
        current = json.loads(output_path.read_text(encoding="utf-8"))
        existing_sources = list(current.get("sources", [])) if isinstance(current, dict) else list(current)
    merged = [
        item for item in existing_sources
        if item.get("source_id") != source_id
        and not str(item.get("source_id", "")).startswith(source_id + "-")
    ]
    merged.extend(sources)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps({"sources": merged}, ensure_ascii=False, indent=2), encoding="utf-8")
    return len(docs)
